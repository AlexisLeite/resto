-- Solo para el entorno Docker local. Se ejecuta al crear un volumen vacío.
CREATE ROLE resto LOGIN PASSWORD 'resto_local' NOSUPERUSER NOCREATEDB NOCREATEROLE;
GRANT CONNECT ON DATABASE resto_dev TO resto;
GRANT USAGE ON SCHEMA public TO resto;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO resto;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO resto;
ALTER DEFAULT PRIVILEGES FOR ROLE resto_migrations IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO resto;
ALTER DEFAULT PRIVILEGES FOR ROLE resto_migrations IN SCHEMA public
  GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO resto;
